import test from "node:test";
import assert from "node:assert/strict";
import { Rally } from "../games/table-tennis/logic.js";
import { Duel } from "../games/swordplay/logic.js";
test("human tennis alternates serve and wins by two", () => {
  const r = new Rally({ winScore: 7 });
  r.setOpponent(0.5, 0.5);
  r.start(0);
  r.scorePoint("ai", "test", 0);
  assert.equal(r.nextServer, "player");
  r.scorePoint("player", "test", 1);
  assert.equal(r.nextServer, "ai");
  r.score = { player: 6, ai: 6 };
  r.scorePoint("player", "test", 2);
  assert.notEqual(r.state, "over");
  r.scorePoint("player", "test", 3);
  assert.equal(r.winner, "player");
});
test("simultaneous deciding fencing hits go to sudden death", () => {
  const d = new Duel();
  d.start(0);
  d.setOpponent(0);
  d.bladeAngle = 0;
  d.player.points = 2;
  d.ai.points = 2;
  d.humanStrike(0, 0, 0);
  d.humanStrike(1, 0, 0);
  d.update(500, 0.01);
  assert.equal(d.player.points, 3);
  assert.equal(d.ai.points, 3);
  assert.equal(d.state, "point");
  assert.equal(d.winner, null);
});
